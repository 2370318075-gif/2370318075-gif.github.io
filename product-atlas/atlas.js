  let activeProduct = "answerloom";
  let activeIndex = 0;

  const chapterOrder = ["muyu", "minuteflow", "answerloom"];
  const outro = document.querySelector(".atlas-outro");
  if (outro) {
    chapterOrder.forEach((productId) => {
      const chapter = document.querySelector(
        `.product-chapter[data-product="${productId}"]`,
      );
      if (chapter) outro.parentElement.insertBefore(chapter, outro);
    });
  }

  function setDialogContent(productId, index) {
    const product = products[productId];
    const node = product.nodes[index];
    if (!node) return;

    activeProduct = productId;
    activeIndex = index;
    productEl.textContent = product.name;
    groupEl.textContent = node.group;
    numberEl.textContent = String(index + 1).padStart(2, "0");
    titleEl.textContent = node.label;
    summaryEl.textContent = node.summary;
    detailEl.textContent = node.detail;
    progressEl.textContent = `${String(index + 1).padStart(2, "0")} / ${String(product.nodes.length).padStart(2, "0")}`;
  }

  function openNode(productId, index) {
    setDialogContent(productId, index);
    document.body.classList.add("dialog-open");
    if (!dialog.open) dialog.showModal();
  }

  function closeDialog() {
    if (dialog.open) dialog.close();
  }

  function moveNode(direction) {
    const count = products[activeProduct].nodes.length;
    const nextIndex = (activeIndex + direction + count) % count;
    setDialogContent(activeProduct, nextIndex);
  }

  function renderHotspots() {
    document.querySelectorAll(".product-chapter[data-product]").forEach((section) => {
      const productId = section.dataset.product;
      const product = products[productId];
      const layer = section.querySelector(".hotspot-layer");
      if (!product || !layer) return;

      product.nodes.forEach((node, index) => {
        const button = document.createElement("button");
        button.type = "button";
        button.className = "atlas-hotspot";
        button.style.left = `${node.x}%`;
        button.style.top = `${node.y}%`;
        button.style.width = `${node.w}%`;
        button.style.height = `${node.h}%`;
        button.setAttribute("aria-label", `查看“${node.label}”说明`);
        button.title = node.label;
        button.addEventListener("click", () => openNode(productId, index));
        layer.append(button);
      });
    });
  }

